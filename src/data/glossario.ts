const chaves = Object.keys(GLOSSARIO).sort((a, b) => b.length - a.length)
const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const RE = new RegExp(`(?<![\\p{L}])(${chaves.map(esc).join('|')})(?![\\p{L}])`, 'giu')

export function definicao(termo: string): string | undefined {
  const k = termo.toLowerCase()
  return GLOSSARIO[k] ?? GLOSSARIO[Object.keys(GLOSSARIO).find(c => c.toLowerCase() === k) ?? '']
}

// Divide um texto em pedaços: texto comum e termos do glossário (cada termo só na 1ª ocorrência).
export function marcarTermos(texto: string): Array<{ t: string; termo?: boolean }> {
  const vistos = new Set<string>(); const out: Array<{ t: string; termo?: boolean }> = []; let i = 0
  for (const m of texto.matchAll(RE)) {
    const k = m[0].toLowerCase(); if (vistos.has(k)) continue; vistos.add(k)
    if (m.index! > i) out.push({ t: texto.slice(i, m.index) })
    out.push({ t: m[0], termo: true }); i = m.index! + m[0].length
  }
  if (i < texto.length) out.push({ t: texto.slice(i) })
  return out
}
