// @vitest-environment jsdom
import { describe, it, expect, vi, beforeEach } from 'vitest'
import { render, screen, fireEvent, cleanup, within, waitFor } from '@testing-library/react'
import { MemoryRouter, Routes, Route } from 'react-router-dom'
import type { Fornecedor } from '@/lib/fornecedores'
import { mesAtual } from '@/lib/fornecedores'

const emDias = (n: number) => { const d = new Date(); d.setHours(12, 0, 0, 0); d.setDate(d.getDate() + n); return d.toISOString().slice(0, 10) }
const br = (iso: string) => iso.split('-').reverse().join('/')
let fornecedor: Fornecedor | null = null
const padrao = (): Fornecedor => ({ id: 'f1', nome: 'Limpa Tudo Ltda', cnpj: '12345678000195', categoria: 'limpeza', imovelIds: ['i1'], kyc: { ceis: 'nao_verificado', cnep: 'nao_verificado' }, certidoes: [{ id: 'c1', nome: 'CRF — FGTS', validade: emDias(10) }, { id: 'c2', nome: 'CNDT — Trabalhista', validade: emDias(-5) }], slas: [{ id: 's1', descricao: 'Vistorias no prazo', unidade: '%', meta: 95, sentido: 'minimo', medicoes: [{ mes: '2026-09', valor: 97 }, { mes: '2026-10', valor: 90 }] }], ocorrencias: [{ id: 'o1', data: emDias(-20), tipo: 'atraso', descricao: 'Vistoria entregue 3 dias depois' }, { id: 'o2', data: emDias(-40), tipo: 'elogio', descricao: 'Equipe elogiada pelo síndico' }] } as Fornecedor)
const salvar = vi.fn(async (_f: Fornecedor, _r: string) => undefined)
const consultar = vi.fn(async (_c: string) => ({ razaoSocial: 'LIMPA TUDO SERVICOS LTDA', situacao: 'ATIVA' }))
vi.mock('@/lib/fornecedores', async (orig) => ({ ...(await orig() as object), obterFornecedor: async (_id: string) => fornecedor, salvarFornecedor: (f: Fornecedor, r: string) => salvar(f, r), consultarCnpj: (c: string) => consultar(c) }))
vi.mock('@/components/Layout', () => ({ default: ({ title, children }: { title: string; children: React.ReactNode }) => <div><h1>{title}</h1>{children}</div> }))
const { default: FornecedorPage } = await import('./FornecedorPage')
const montar = () => render(<MemoryRouter initialEntries={['/fornecedor/f1']}><Routes><Route path="/fornecedor/:id" element={<FornecedorPage />} /></Routes></MemoryRouter>)
const secao = (id: string) => document.querySelector(`section[aria-labelledby="${id}"]`) as HTMLElement
const ultimo = () => salvar.mock.calls[salvar.mock.calls.length - 1]

describe('Ficha do fornecedor', () => {
  beforeEach(() => { cleanup(); fornecedor = padrao(); salvar.mockClear(); consultar.mockClear() })

  it('carrega a ficha com categoria, CNPJ formatado, KYC com pendências, certidões por prazo, ocorrências ordenadas e SLA com medições; consulta à Receita e listas CEIS/CNEP gravam', async () => {
    const write = vi.fn(async (_t: string) => undefined); Object.assign(navigator, { clipboard: { writeText: write } })
    montar()
    expect(screen.getByText('Carregando…')).toBeTruthy()
    await waitFor(() => expect(screen.getByRole('heading', { level: 1 }).textContent).toBe('Limpa Tudo Ltda'))
    expect(screen.getByText('Limpeza e conservação')).toBeTruthy(); expect(screen.getByText('CNPJ 12.345.678/0001-95')).toBeTruthy()
    expect(screen.getByText('Voltar aos fornecedores').closest('a')!.getAttribute('href')).toBe('/fornecedores')
    fireEvent.click(screen.getByTestId('copiar-link-fornecedor')); expect(write).toHaveBeenCalledWith(window.location.href)
    const kyc = secao('kyc')
    expect(kyc.textContent).toContain('Irregular'); expect(within(kyc).getByText('CNPJ ainda não consultado na Receita')).toBeTruthy(); expect(within(kyc).getAllByRole('listitem').length).toBeGreaterThanOrEqual(2); expect(within(kyc).getByText('Ainda não consultado.')).toBeTruthy()
    expect(within(kyc).getAllByText('Consultar no Portal da Transparência')[0].closest('a')!.getAttribute('href')).toBe('https://portaldatransparencia.gov.br/sancoes/consulta?cadastro=1&cpfCnpj=12345678000195')
    const cert = secao('certidoes')
    const itens = within(cert).getAllByRole('listitem')
    expect(itens[0].textContent).toContain('CRF — FGTS'); expect(itens[0].textContent).toContain(`Validade ${br(emDias(10))}`); expect(itens[0].textContent).toContain('Vence em 10 dias')
    expect(itens[1].textContent).toContain('Vencido há 5 dias')
    const oc = within(screen.getByTestId('ocorrencias')).getAllByTestId('ocorrencia')
    expect(oc[0].textContent).toContain('Atraso'); expect(oc[0].textContent).toContain('Vistoria entregue 3 dias depois'); expect(within(oc[0]).getByText('marcar como resolvida')).toBeTruthy()
    expect(oc[1].textContent).toContain('Elogio'); expect(within(oc[1]).queryByText('marcar como resolvida')).toBeNull()
    expect(screen.getByTestId('sla-pct').textContent).toBe('45% de SLA cumprido')
    const sla = secao('sla')
    expect(sla.textContent).toContain('Vistorias no prazo'); expect(sla.textContent).toContain('Meta: no mínimo 95% por mês'); expect(sla.textContent).toContain('Descumprido')
    const med = within(sla).getAllByRole('listitem')
    expect(med.length).toBe(2); expect(med[0].textContent).toContain('97%'); expect(within(med[0]).getByLabelText('cumprido')).toBeTruthy(); expect(within(med[1]).getByLabelText('descumprido')).toBeTruthy(); expect(med[1].textContent).toContain('10/2026')
    fireEvent.click(screen.getByText('Consultar CNPJ agora'))
    expect(screen.getByText('Consultando…')).toBeTruthy()
    await waitFor(() => expect(screen.getByRole('status').textContent).toBe('Receita Federal: LIMPA TUDO SERVICOS LTDA, situação ATIVA.'))
    expect(consultar).toHaveBeenCalledWith('12345678000195')
    expect(ultimo()[0].kyc).toMatchObject({ razaoSocial: 'LIMPA TUDO SERVICOS LTDA', situacao: 'ATIVA', consultadoEm: new Date().toISOString().slice(0, 10) }); expect(ultimo()[1]).toBe('CNPJ consultado na Receita: Limpa Tudo Ltda (ATIVA)')
    expect(within(secao('kyc')).getByText('ATIVA')).toBeTruthy()
    fireEvent.click(within(within(secao('kyc')).getByRole('radiogroup', { name: 'Resultado CEIS' })).getByLabelText('Nada consta'))
    await waitFor(() => expect(ultimo()[1]).toBe('CEIS verificado manualmente: Limpa Tudo Ltda (limpo)'))
    fireEvent.click(within(within(secao('kyc')).getByRole('radiogroup', { name: 'Resultado CNEP' })).getByLabelText('Consta sanção'))
    await waitFor(() => expect(ultimo()[1]).toBe('CNEP verificado manualmente: Limpa Tudo Ltda (sancionado)'))
    expect(ultimo()[0].kyc).toMatchObject({ ceis: 'limpo', cnep: 'sancionado', listasVerificadasEm: new Date().toISOString().slice(0, 10) })
    await waitFor(() => expect(secao('kyc').textContent).toContain('Irregular'))
    consultar.mockRejectedValueOnce(new Error('CNPJ não encontrado na Receita Federal.'))
    fireEvent.click(screen.getByText('Consultar CNPJ agora'))
    await waitFor(() => expect(screen.getByRole('alert').textContent).toBe('CNPJ não encontrado na Receita Federal.'))
  })

  it('certidões: validade obrigatória, registra e remove; ocorrências: botão por tamanho, registra e marca como resolvida; erro ao salvar explicado', async () => {
    montar()
    await waitFor(() => expect(screen.getByRole('heading', { level: 1 }).textContent).toBe('Limpa Tudo Ltda'))
    fireEvent.click(within(secao('certidoes')).getByText('Registrar'))
    expect(screen.getByRole('alert').textContent).toBe('Informe a data de validade da certidão.')
    fireEvent.change(screen.getByLabelText('Certidão'), { target: { value: 'Certidão Municipal' } })
    fireEvent.change(screen.getByLabelText('Validade'), { target: { value: emDias(200) } })
    fireEvent.click(within(secao('certidoes')).getByText('Registrar'))
    await waitFor(() => expect(screen.getByRole('status').textContent).toBe('Certidão registrada.'))
    expect(ultimo()[1]).toBe('Certidão registrada: Certidão Municipal (Limpa Tudo Ltda)')
    expect(ultimo()[0].certidoes.length).toBe(3); expect(ultimo()[0].certidoes[2]).toMatchObject({ nome: 'Certidão Municipal', validade: emDias(200) })
    expect(within(secao('certidoes')).getAllByRole('listitem').length).toBe(3)
    expect((screen.getByLabelText('Validade') as HTMLInputElement).value).toBe('')
    fireEvent.click(screen.getByRole('button', { name: 'Remover CNDT — Trabalhista' }))
    await waitFor(() => expect(within(secao('certidoes')).getAllByRole('listitem').length).toBe(2))
    expect(ultimo()[1]).toBe('Certidão removida (Limpa Tudo Ltda)'); expect(ultimo()[0].certidoes.map((c: { nome: string }) => c.nome)).toEqual(['CRF — FGTS', 'Certidão Municipal'])
    expect((screen.getByTestId('registrar-ocorrencia') as HTMLButtonElement).disabled).toBe(true)
    fireEvent.change(screen.getByLabelText('Tipo'), { target: { value: 'reclamacao' } })
    fireEvent.change(screen.getByLabelText('Data'), { target: { value: emDias(-1) } })
    fireEvent.change(screen.getByLabelText('O que aconteceu'), { target: { value: '  Faltou material no dia 3 ' } })
    expect((screen.getByTestId('registrar-ocorrencia') as HTMLButtonElement).disabled).toBe(false)
    fireEvent.click(screen.getByTestId('registrar-ocorrencia'))
    await waitFor(() => expect(screen.getByRole('status').textContent).toBe('Ocorrência registrada.'))
    expect(ultimo()[1]).toBe('Ocorrência registrada: Limpa Tudo Ltda — Reclamação')
    expect(ultimo()[0].ocorrencias![2]).toMatchObject({ data: emDias(-1), tipo: 'reclamacao', descricao: 'Faltou material no dia 3' })
    const oc = within(screen.getByTestId('ocorrencias')).getAllByTestId('ocorrencia')
    expect(oc.length).toBe(3); expect(oc[0].textContent).toContain('Reclamação'); expect(oc[0].textContent).toContain('Faltou material no dia 3')
    expect(screen.getByTestId('sla-pct').textContent).toBe('40% de SLA cumprido')
    fireEvent.click(within(oc[0]).getByText('marcar como resolvida'))
    await waitFor(() => expect(screen.getByRole('status').textContent).toBe('Ocorrência marcada como resolvida.'))
    expect(ultimo()[0].ocorrencias![2].resolvidaEm).toBe(new Date().toISOString().slice(0, 10))
    expect(within(screen.getByTestId('ocorrencias')).getAllByTestId('ocorrencia')[0].textContent).toContain(`resolvida em ${br(new Date().toISOString().slice(0, 10))}`)
    expect(screen.getByTestId('sla-pct').textContent).toBe('45% de SLA cumprido')
    salvar.mockRejectedValueOnce(new Error('sem conexão'))
    fireEvent.click(within(within(screen.getByTestId('ocorrencias')).getAllByTestId('ocorrencia')[1]).getByText('marcar como resolvida'))
    await waitFor(() => expect(screen.getByRole('alert').textContent).toContain('sem conexão'))
  })

  it('SLA: nova meta exige descrição, número e sentido; medição do mês exige número e informa se cumpriu; fornecedor inexistente', async () => {
    montar()
    await waitFor(() => expect(screen.getByRole('heading', { level: 1 }).textContent).toBe('Limpa Tudo Ltda'))
    fireEvent.click(screen.getByText('Criar meta'))
    expect(screen.getByRole('alert').textContent).toBe('Descreva o SLA e informe a meta (número).')
    fireEvent.change(screen.getByLabelText('O que será medido'), { target: { value: 'Tempo de resposta a chamados' } })
    fireEvent.change(screen.getByLabelText('Meta (número)'), { target: { value: '2,5' } })
    fireEvent.change(screen.getByLabelText('Unidade'), { target: { value: 'h' } })
    fireEvent.click(screen.getByText('Criar meta'))
    expect(screen.getByRole('alert').textContent).toBe('Escolha se a meta é um mínimo ou um máximo.')
    fireEvent.click(within(screen.getByRole('radiogroup', { name: 'Tipo de meta' })).getByRole('radio', { name: /^Máximo/ }))
    fireEvent.click(screen.getByText('Criar meta'))
    await waitFor(() => expect(screen.getByRole('status').textContent).toBe('SLA criado.'))
    expect(ultimo()[1]).toBe('SLA criado: Tempo de resposta a chamados (Limpa Tudo Ltda)')
    expect(ultimo()[0].slas[1]).toMatchObject({ descricao: 'Tempo de resposta a chamados', unidade: 'h', meta: 2.5, sentido: 'maximo', medicoes: [] })
    expect(secao('sla').textContent).toContain('Meta: no máximo 2.5h por mês'); expect(secao('sla').textContent).toContain('Sem medição')
    const campo = screen.getByLabelText(`Resultado de ${mesAtual().slice(5, 7)}/${mesAtual().slice(0, 4)}`, { selector: `#med-${ultimo()[0].slas[1].id}` })
    fireEvent.click(within(campo.closest('div.border') as HTMLElement).getByText('Registrar medição do mês'))
    expect(screen.getByRole('alert').textContent).toBe('Informe o resultado do mês como número.')
    fireEvent.change(campo, { target: { value: '1,8' } })
    fireEvent.click(within(campo.closest('div.border') as HTMLElement).getByText('Registrar medição do mês'))
    await waitFor(() => expect(screen.getByRole('status').textContent).toBe('Medição registrada: meta cumprida.'))
    expect(ultimo()[0].slas[1].medicoes).toEqual([{ mes: mesAtual(), valor: 1.8 }])
    expect(ultimo()[1]).toBe(`Medição de SLA: Tempo de resposta a chamados = 1.8h em ${mesAtual()} (Limpa Tudo Ltda)`)
    const primeiro = screen.getByLabelText(`Resultado de ${mesAtual().slice(5, 7)}/${mesAtual().slice(0, 4)}`, { selector: '#med-s1' })
    fireEvent.change(primeiro, { target: { value: '80' } })
    fireEvent.click(within(primeiro.closest('div.border') as HTMLElement).getByText('Registrar medição do mês'))
    await waitFor(() => expect(screen.getByRole('status').textContent).toBe('Medição registrada: meta DESCUMPRIDA.'))
    expect(ultimo()[0].slas[0].medicoes.length).toBe(3)
    cleanup(); fornecedor = null
    montar()
    await waitFor(() => expect(screen.getByRole('heading', { level: 1 }).textContent).toBe('Fornecedor não encontrado'))
    expect(screen.getByText('Voltar aos fornecedores').closest('a')!.getAttribute('href')).toBe('/fornecedores')
  })
})
