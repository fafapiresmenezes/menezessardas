// @vitest-environment jsdom
import { describe, it, expect, vi, beforeEach } from 'vitest'
import { render, screen, fireEvent, cleanup, within, waitFor } from '@testing-library/react'
import { MemoryRouter } from 'react-router-dom'

const nb = (s: string | null | undefined) => (s ?? '').replace(/ /g, ' ')
const contrato = (id: string, parte: string) => ({ id, imovelId: 'i1', tipo: 'locacao_residencial', parte, dataInicio: '2025-01-01', dataVencimento: '2027-01-01', valor: 3000, periodicidade: 'mensal', indice: 'igpm', garantia: 'caucao', dataUltimoReajuste: null, notas: '', criadoEm: '2025-01-01', documentos: [] })
const imovel = { id: 'i1', endereco: 'Rua das Flores 123', cidade: 'Rio', uf: 'RJ', tipo: 'apartamento', uso: 'locado', proprietario: 'X', matricula: '1', notas: '', documentos: [] }
let previsoes = [
  { contrato: contrato('c1', 'Ana Locatária'), imovel, risco: 72, faixaRisco: 'alto', fatoresRisco: [{ fator: 'Sem garantia', pontos: 30 }, { fator: 'Vencimento próximo', pontos: 20 }, { fator: 'Documentos vencidos', pontos: 12 }, { fator: 'Reajuste atrasado', pontos: 10 }], renovacao: 35, fatoresRenovacao: [{ fator: 'Preço acima da carteira', pontos: -20 }, { fator: 'Contrato longo', pontos: 10 }], acao: 'Negociar garantia e renovação antecipada.' },
  { contrato: contrato('c2', 'Bruno Inquilino'), imovel, risco: 18, faixaRisco: 'baixo', fatoresRisco: [], renovacao: 80, fatoresRenovacao: [{ fator: 'Preço na média', pontos: 10 }], acao: 'Acompanhar.' },
]
let receita = [{ mes: 'nov', contratada: 6000, esperada: 6000 }, { mes: 'dez', contratada: 6000, esperada: 6200 }]
let configurado = true
const registrar = vi.fn()
const invoke = vi.fn(async (nome: string, _o: object): Promise<{ data?: Record<string, unknown>; error: { message: string } | null }> => nome === 'indice-reajuste' ? { data: { acumulado12m: 3.5 }, error: null } : { data: {}, error: null })
const rpc = vi.fn(async (_n: string, _a: object): Promise<{ data: unknown; error: { message: string } | null }> => ({ data: 2, error: null }))
const consultarInstituto = vi.fn(async (_b: object) => ({ convencional: { p: 0.874, ic95: [0.82, 0.91] as [number, number], n: 1200 }, grafo: { p: 0.9 }, confianca: 'alta', placar_atual: 'inconclusivo', aviso: 'Não é garantia.', fonte: 'Instituto THEYE' }))
vi.mock('@/lib/supabase', () => ({ get supabaseConfigurado() { return configurado }, supabase: { functions: { invoke: (n: string, o: object) => invoke(n, o) }, rpc: (n: string, a: object) => rpc(n, a) } }))
vi.mock('@/hooks/useImoveis', () => ({ useImoveis: () => ({ imoveis: [imovel], loading: false }) }))
vi.mock('@/lib/repositorio', () => ({ repositorio: { listarContratos: async () => previsoes.map(p => p.contrato) } }))
vi.mock('@/lib/predicao', async (orig) => ({ ...(await orig() as object), preverCarteira: () => previsoes, preverReceita: () => receita, registrarPrevisoes: (l: unknown) => registrar(l) }))
vi.mock('@/lib/previsaoInstituto', async (orig) => ({ ...(await orig() as object), consultarPrevisaoInstituto: (b: object) => consultarInstituto(b) }))
vi.mock('@/components/CalibracaoPrevisoes', () => ({ default: ({ versao }: { versao: number }) => <div data-testid="calibracao-stub">v{versao}</div> }))
vi.mock('@/components/Layout', () => ({ default: ({ title, children }: { title: string; children: React.ReactNode }) => <div><h1>{title}</h1>{children}</div> }))
const { default: PrevisoesPage } = await import('./PrevisoesPage')
const montar = () => render(<MemoryRouter><PrevisoesPage /></MemoryRouter>)
const cartao = (r: string) => nb(screen.getByText(r).nextElementSibling!.textContent)
const juri = () => document.querySelector('section[aria-labelledby="t-juri"]') as HTMLElement

describe('Previsões', () => {
  const write = vi.fn(async (_t: string) => undefined)
  beforeEach(() => { cleanup(); localStorage.clear(); configurado = true; registrar.mockClear(); write.mockClear(); rpc.mockClear(); consultarInstituto.mockClear(); invoke.mockReset().mockImplementation(async (nome: string) => nome === 'indice-reajuste' ? { data: { acumulado12m: 3.5 }, error: null } : { data: {}, error: null }); Object.assign(navigator, { clipboard: { writeText: write } }) })

  it('cartões da carteira, receita com índices do Banco Central, linha por contrato com fatores, ação e desfecho que calibra; fotografia diária registrada uma vez', async () => {
    montar()
    await waitFor(() => expect(screen.getByText(/Banco Central: IGPM 3,5%, IPCA 3,5%, INPC 3,5%/)).toBeTruthy())
    expect(cartao('Receita contratada (12 meses)')).toBe('R$ 12.000'); expect(cartao('Receita esperada (12 meses)')).toBe('R$ 12.200')
    expect(cartao('Contratos com risco alto')).toBe('1'); expect(cartao('Chance média de renovação')).toBe('58%')
    expect(screen.getByRole('img', { name: 'Receita prevista para os próximos 12 meses' }).children.length).toBe(2)
    await waitFor(() => expect(registrar).toHaveBeenCalledTimes(1))
    const lote = registrar.mock.calls[0][0] as { tipo: string; referencia?: string; previsto: Record<string, unknown> }[]
    expect(lote.map(l => l.tipo)).toEqual(['risco_contrato', 'risco_contrato', 'receita'])
    expect(lote[0]).toMatchObject({ referencia: 'c1', previsto: { risco: 72, faixa: 'alto', renovacao: 35, fatores: ['Sem garantia', 'Vencimento próximo', 'Documentos vencidos', 'Reajuste atrasado'] } })
    expect(localStorage.getItem(`lsm-previsoes-${new Date().toISOString().slice(0, 10)}`)).toBe('1')
    const linhas = within(document.querySelector('section[aria-labelledby="t-risco"]') as HTMLElement).getAllByRole('listitem')
    expect(linhas.length).toBe(2)
    expect(linhas[0].textContent).toContain('Ana Locatária'); expect(linhas[0].textContent).toContain('Risco alto (72)'); expect(linhas[0].textContent).toContain('Renovação ~35%')
    expect(within(linhas[0]).getByTestId('motivos').textContent).toBe('Pesou mais: sem garantia; vencimento próximo; documentos vencidos')
    expect(within(linhas[1]).queryByTestId('motivos')).toBeNull(); expect(linhas[1].textContent).toContain('Risco baixo (18)')
    const abrir = within(linhas[0]).getByRole('button', { expanded: false })
    fireEvent.click(abrir)
    expect(abrir.getAttribute('aria-expanded')).toBe('true')
    expect(within(linhas[0]).getByText('Sem garantia').nextElementSibling!.textContent).toBe('+30')
    expect(within(linhas[0]).getByText('Preço acima da carteira').nextElementSibling!.textContent).toBe('-20')
    expect(within(linhas[0]).getByText('Negociar garantia e renovação antecipada.', { exact: false })).toBeTruthy()
    expect(within(linhas[0]).getByText('Abrir contrato').getAttribute('href')).toBe('/contrato/c1')
    expect(screen.getByTestId('calibracao-stub').textContent).toBe('v0')
    fireEvent.click(within(linhas[0]).getByText('Ficou inadimplente'))
    await waitFor(() => expect(screen.getByTestId('msg-desfecho').textContent).toBe('Desfecho registrado (2 previsões). A calibração já considera.'))
    expect(rpc).toHaveBeenCalledWith('registrar_desfecho', { p_referencia: 'c1', p_desfecho: { inadimplente: true } })
    expect(screen.getByTestId('calibracao-stub').textContent).toBe('v1')
    rpc.mockResolvedValueOnce({ data: 0, error: null })
    fireEvent.click(within(linhas[0]).getByText('Renovou'))
    await waitFor(() => expect(screen.getByTestId('msg-desfecho').textContent).toContain('Ainda não há previsão gravada para este contrato'))
    rpc.mockResolvedValueOnce({ data: null, error: { message: 'permission denied for table registro_previsoes' } })
    fireEvent.click(within(linhas[0]).getByText('Pagou em dia'))
    await waitFor(() => expect(screen.getByTestId('msg-desfecho').textContent).toContain('Não deu para registrar:'))
    cleanup(); montar()
    await waitFor(() => expect(screen.getByText(/Banco Central: IGPM/)).toBeTruthy())
    expect(registrar).toHaveBeenCalledTimes(1)
  })

  it('jurimetria consulta o CNJ com ação, tribunal e vara lembrada, mostra margem de Wilson e contagens, avisa amostra pequena e sem sentenças, explica erros', async () => {
    localStorage.setItem('lsm-previsoes-orgao', '10ª Vara Cível')
    montar()
    await waitFor(() => expect(screen.getByText(/Banco Central: IGPM/)).toBeTruthy())
    const s = juri()
    expect((within(s).getByPlaceholderText('Ex.: 10ª Vara Cível') as HTMLInputElement).value).toBe('10ª Vara Cível')
    fireEvent.change(within(s).getByLabelText('Ação'), { target: { value: 'renovatoria' } })
    fireEvent.change(within(s).getByLabelText('Tribunal'), { target: { value: 'tjsp' } })
    fireEvent.change(within(s).getByPlaceholderText('Ex.: 10ª Vara Cível'), { target: { value: '2ª Vara Empresarial' } })
    expect(localStorage.getItem('lsm-previsoes-orgao')).toBe('2ª Vara Empresarial')
    const res = { tribunal: 'TJSP', acao: 'Renovatória de Locação', orgao: '2ª Vara Empresarial', processos: 1500, resultados: { procedencia: 300, parcial: 100, improcedencia: 100, semMerito: 50, acordo: 60 }, chanceExito: 70, taxaAcordo: 10, taxaSemMerito: 8, amostra: 500, confianca: 'alta', fonte: 'DataJud', consultadoEm: '2026-11-02T00:00:00Z' }
    invoke.mockResolvedValueOnce({ data: res, error: null })
    fireEvent.click(within(s).getByText('Calcular'))
    expect(within(s).getByText('Consultando o CNJ…')).toBeTruthy()
    await waitFor(() => expect(s.textContent).toContain('70% de êxito do autor'))
    expect(invoke).toHaveBeenCalledWith('jurimetria', { body: { acao: 'renovatoria', tribunal: 'tjsp', orgao: '2ª Vara Empresarial' } })
    expect(nb(s.textContent)).toContain('Margem (95%): entre 66% e 74% · amostra de 500 sentenças · confiança alta')
    expect(within(s).getByText('Procedência').nextElementSibling!.textContent).toBe('300'); expect(within(s).getByText('Acordo').nextElementSibling!.textContent).toBe('60')
    expect(nb(s.textContent)).toContain('Fonte: DataJud · TJSP · Renovatória de Locação · 2ª Vara Empresarial · 1.500 processos')
    expect(registrar).toHaveBeenLastCalledWith([expect.objectContaining({ tipo: 'jurimetria', referencia: 'TJSP|Renovatória de Locação|2ª Vara Empresarial', amostra: 500, fonte: 'DataJud' })])
    invoke.mockResolvedValueOnce({ data: { ...res, confianca: 'baixa', amostra: 12, resultados: { procedencia: 7, parcial: 2, improcedencia: 3, semMerito: 0, acordo: 0 } }, error: null })
    fireEvent.click(within(s).getByText('Calcular'))
    await waitFor(() => expect(s.textContent).toContain('Amostra pequena: use como indício, não como previsão.'))
    expect(s.textContent).toContain('confiança baixa')
    invoke.mockResolvedValueOnce({ data: { ...res, chanceExito: null }, error: null })
    fireEvent.click(within(s).getByText('Calcular'))
    await waitFor(() => expect(s.textContent).toContain('O CNJ não tem sentenças com resultado registrado para esse filtro.'))
    invoke.mockResolvedValueOnce({ data: { erro: 'Tribunal não suportado' }, error: null })
    fireEvent.click(within(s).getByText('Calcular'))
    await waitFor(() => expect(within(s).getByRole('alert').textContent).toBe('Tribunal não suportado'))
    invoke.mockResolvedValueOnce({ error: { message: 'Failed to fetch' } })
    fireEvent.click(within(s).getByText('Calcular'))
    await waitFor(() => expect(within(s).getByRole('alert')).toBeTruthy())
  })

  it('Instituto THEYE: consulta por classe e tribunal, resultado com grafo, aviso e cópia para o parecer; erro; resumo, link, CSV e impressão; demonstração sem banco e carteira vazia', async () => {
    const clique = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => undefined)
    Object.assign(URL, { createObjectURL: vi.fn(() => 'blob:x'), revokeObjectURL: vi.fn() }); window.print = vi.fn()
    montar()
    await waitFor(() => expect(screen.getByText(/Banco Central: IGPM/)).toBeTruthy())
    fireEvent.change(screen.getByTestId('instituto-classe'), { target: { value: 'Renovatória de Locação' } })
    fireEvent.change(screen.getByTestId('instituto-tribunal'), { target: { value: 'TJSP' } })
    fireEvent.click(screen.getByTestId('instituto-calcular'))
    await waitFor(() => expect(screen.getByTestId('instituto-resultado')).toBeTruthy())
    expect(consultarInstituto).toHaveBeenCalledWith({ tribunal: 'TJSP', classe: 'Renovatória de Locação' })
    const r = screen.getByTestId('instituto-resultado')
    expect(r.textContent).toContain('87,4% de procedência'); expect(nb(r.textContent)).toContain('Margem (95%): entre 82,0% e 91,0% · 1.200 processos · confiança alta')
    expect(screen.getByTestId('instituto-grafo').textContent).toBe('Modelo por grafo: 90,0% (placar inconclusivo)')
    expect(screen.getByTestId('instituto-aviso').textContent).toBe('Não é garantia.')
    expect(r.textContent).toContain('Fonte: Instituto THEYE · TJSP · Renovatória de Locação.')
    fireEvent.click(screen.getByTestId('instituto-copiar'))
    await waitFor(() => expect(screen.getByTestId('instituto-copiar').textContent).toBe('Resultado copiado'))
    expect(nb(write.mock.calls[0][0]).split('\n')).toEqual(['Probabilidade do Instituto THEYE — TJSP · Renovatória de Locação', '87,4% de procedência — Margem (95%): entre 82,0% e 91,0% · 1.200 processos · confiança alta', 'Modelo por grafo: 90,0% (placar inconclusivo)', 'Aviso: Não é garantia.', 'Fonte: Instituto THEYE · mede tendência do tribunal, não o processo concreto'])
    consultarInstituto.mockRejectedValueOnce(new Error('A API do Instituto não respondeu.'))
    fireEvent.click(screen.getByTestId('instituto-calcular'))
    await waitFor(() => expect(screen.getByTestId('instituto-erro').textContent).toBe('A API do Instituto não respondeu.'))
    fireEvent.click(screen.getByTestId('copiar-previsoes'))
    await waitFor(() => expect(screen.getByTestId('copiar-previsoes').textContent).toBe('Resumo copiado'))
    const resumo = nb(write.mock.calls[1][0]).split('\n')
    expect(resumo.slice(1)).toEqual(['Receita contratada (12 meses): R$ 12.000', 'Receita esperada (12 meses): R$ 12.200', 'Contratos com risco alto: 1 de 2', 'Chance média de renovação: 58%', '• risco alto: Ana Locatária (72 pontos)', 'Regras declaradas v1 · Instituto THEYE'])
    fireEvent.click(screen.getByTestId('copiar-link-previsoes'))
    await waitFor(() => expect(screen.getByTestId('copiar-link-previsoes').textContent).toBe('Link copiado'))
    fireEvent.click(screen.getByTestId('baixar-previsoes'))
    expect(screen.getByTestId('baixar-previsoes').textContent).toBe('Baixado'); expect(clique).toHaveBeenCalledTimes(1)
    fireEvent.click(screen.getByTestId('imprimir-previsoes')); expect(window.print).toHaveBeenCalled()
    cleanup(); configurado = false; invoke.mockClear(); previsoes = []; receita = []
    montar()
    await waitFor(() => expect(screen.getByText(/Banco Central: IGPM 3,35%, IPCA 4,5%, INPC 4,3%/)).toBeTruthy())
    expect(invoke).not.toHaveBeenCalled()
    expect(screen.getByText('Nenhum contrato vigente')).toBeTruthy()
    expect(screen.getByText('Cadastrar contrato').getAttribute('href')).toBe('/contrato/novo')
    expect(cartao('Chance média de renovação')).toBe('0%')
    fireEvent.click(within(juri()).getByText('Calcular'))
    await waitFor(() => expect(juri().textContent).toContain('81% de êxito do autor'))
    expect(juri().textContent).toContain('Exemplo da demonstração')
    fireEvent.click(screen.getByTestId('instituto-calcular'))
    await waitFor(() => expect(screen.getByTestId('instituto-resultado').textContent).toContain('97,4% de procedência'))
    expect(consultarInstituto).toHaveBeenCalledTimes(2)
    clique.mockRestore()
  })
})
