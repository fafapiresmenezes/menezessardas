// @vitest-environment jsdom
import { describe, it, expect, vi, beforeEach } from 'vitest'
import { render, screen, fireEvent, cleanup, within, waitFor } from '@testing-library/react'
import type { EventoTrilha, ResultadoVerificacao } from '@/lib/trilha'
import type { Ancoragem, Lastro } from '@/lib/ancoragem'

const agora = Date.now()
const horasAtras = (h: number) => new Date(agora - h * 3600000).toISOString()
const ev = (seq: number, tipo: EventoTrilha['tipo'], resumo: string, em: string): EventoTrilha => ({ id: `e${seq}`, seq, em, tipo, entidade: 'x', resumo, hashAnterior: '0'.repeat(64), hash: `${seq}`.repeat(64).slice(0, 64) })
let eventos: EventoTrilha[] = []
let verificacao: ResultadoVerificacao = { integra: true, total: 0, selo: 'abc123' }
let ancoragens: Ancoragem[] = []
let lastros: Lastro[] = []
const ancorar = vi.fn(async (): Promise<Ancoragem> => ({ id: 'a9', seq: 3, selo: 's9', digest: 'ab', calendario: 'https://alice', provaB64: 'AA==', em: horasAtras(0) }))
const baixar = vi.fn((_n: string, _c: unknown, _t?: string) => undefined)
const exportar = vi.fn(async (_de: string, _ate: string) => ({ nomeBase: 'trilha-2026-10', pdf: new Uint8Array([1]), ots: new Uint8Array([2]), sha256: 'f'.repeat(64), total: 2, calendario: 'https://alice.btc.calendar.opentimestamps.org' }))
vi.mock('@/lib/trilha', () => ({ listarTrilha: async () => eventos, verificarTrilha: async () => verificacao }))
vi.mock('@/lib/ancoragem', async (orig) => ({ ...(await orig() as object), ancorarAgora: () => ancorar(), baixarArquivo: (n: string, c: unknown, t?: string) => baixar(n, c, t), listarAncoragens: async () => ancoragens, verificarLastro: async () => lastros, montarOts: () => new Uint8Array([7]) }))
vi.mock('@/lib/exportarTrilha', () => ({ exportarTrilhaPeriodo: (de: string, ate: string) => exportar(de, ate) }))
vi.mock('@/components/Layout', () => ({ default: ({ title, children }: { title: string; children: React.ReactNode }) => <div><h1>{title}</h1>{children}</div> }))
const { default: TrilhaPage } = await import('./TrilhaPage')
const registros = () => within(screen.getByRole('region', { name: 'Registros da trilha' })).queryAllByRole('listitem').map(l => l.textContent!)
const ancSec = () => document.querySelector('section[aria-labelledby="ancoragem"]') as HTMLElement
const padrao = () => [ev(1, 'imovel_criado', 'Imóvel Rua das Flores 123 cadastrado', horasAtras(50)), ev(2, 'contrato_criado', 'Contrato com Ana Locatária', horasAtras(26)), ev(3, 'documento_anexado', 'IPTU anexado ao imóvel Rua das Flores 123', horasAtras(1))]

describe('Trilha de auditoria', () => {
  const write = vi.fn(async (_t: string) => undefined)
  beforeEach(() => { cleanup(); localStorage.clear(); eventos = padrao(); verificacao = { integra: true, total: 3, selo: 'abc123' }; ancoragens = []; lastros = []; ancorar.mockClear(); baixar.mockClear(); exportar.mockClear(); write.mockClear(); Object.assign(navigator, { clipboard: { writeText: write } }); Object.assign(URL, { createObjectURL: vi.fn(() => 'blob:x'), revokeObjectURL: vi.fn() }); window.print = vi.fn() })

  it('verifica a cadeia, lista os registros do mais recente ao mais antigo, filtra por ação, texto lembrado e dia; copiar registros, CSV, link e imprimir', async () => {
    localStorage.setItem('lsm-trilha-texto', 'flores')
    render(<TrilhaPage />)
    expect(screen.getByText('Verificando a cadeia…')).toBeTruthy()
    await waitFor(() => expect(screen.getByText('Cadeia íntegra — 3 registro(s) verificado(s).')).toBeTruthy())
    expect(screen.getByText('Selo atual: abc123')).toBeTruthy()
    expect(screen.getByTestId('contagem-trilha').textContent).toBe('2 de 3 registros')
    expect(registros().map(r => r.slice(0, 6))).toEqual(['nº 3Do', 'nº 1Im'])
    fireEvent.click(screen.getByText('Limpar'))
    expect(registros().length).toBe(3)
    expect(registros()[0]).toContain('Documento anexado'); expect(registros()[0]).toContain('hash: 333333333333333333333333…')
    fireEvent.change(screen.getByTestId('filtro-tipo'), { target: { value: 'contrato_criado' } })
    expect(registros().length).toBe(1); expect(registros()[0]).toContain('Contrato com Ana Locatária')
    fireEvent.change(screen.getByTestId('filtro-tipo'), { target: { value: '' } })
    fireEvent.change(screen.getByTestId('filtro-texto'), { target: { value: 'ANA' } })
    expect(localStorage.getItem('lsm-trilha-texto')).toBe('ANA'); expect(registros().length).toBe(1)
    fireEvent.change(screen.getByTestId('filtro-texto'), { target: { value: '' } })
    fireEvent.change(screen.getByTestId('filtro-dia'), { target: { value: horasAtras(1).slice(0, 10) } })
    expect(registros().every(r => r.includes('nº 3') || r.includes('nº 2'))).toBe(true)
    fireEvent.click(screen.getByText('Limpar'))
    const clique = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => undefined)
    fireEvent.click(screen.getByTestId('copiar-registros'))
    await waitFor(() => expect(screen.getByTestId('copiar-registros').textContent).toBe('Copiados'))
    const linhas = write.mock.calls[0][0].split('\n')
    expect(linhas[0]).toBe('Trilha de auditoria — 3 registro(s)'); expect(linhas[1]).toContain('nº 3 ·'); expect(linhas[1]).toContain('· Documento anexado · IPTU anexado ao imóvel Rua das Flores 123 · hash 3333333333333333…')
    fireEvent.click(screen.getByTestId('baixar-trilha'))
    expect(screen.getByTestId('baixar-trilha').textContent).toBe('Baixado'); expect(clique).toHaveBeenCalledTimes(1)
    fireEvent.click(screen.getByTestId('copiar-link-trilha'))
    await waitFor(() => expect(screen.getByTestId('copiar-link-trilha').textContent).toBe('Link copiado'))
    fireEvent.click(screen.getByTestId('imprimir-registros')); expect(window.print).toHaveBeenCalled()
    clique.mockRestore()
    cleanup(); verificacao = { integra: false, total: 3, quebraEm: 2, selo: 'zzz' }
    render(<TrilhaPage />)
    await waitFor(() => expect(screen.getByText('Cadeia comprometida a partir do registro nº 2.')).toBeTruthy())
    expect((screen.getByText('Ancorar selo agora').closest('button') as HTMLButtonElement).disabled).toBe(true)
  })

  it('ancoragem: estado do selo em dia ou atrasado, ancorar agora, verificar lastro, baixar selo e prova, copiar selos e último selo, CSV, imprimir e link; erro explicado', async () => {
    ancoragens = [{ id: 'a1', seq: 1, selo: 'selo-um-'.padEnd(40, '1'), digest: 'ab', calendario: 'https://alice', provaB64: 'AA==', em: horasAtras(30) }, { id: 'a2', seq: 2, selo: 'selo-dois-'.padEnd(40, '2'), digest: 'cd', calendario: 'https://finney', provaB64: 'AA==', em: horasAtras(2) }]
    lastros = [{ ancoragemId: 'a1', seq: 1, coerente: true }, { ancoragemId: 'a2', seq: 2, coerente: false, motivo: 'registro nº 2 reescrito' }]
    render(<TrilhaPage />)
    await waitFor(() => expect(screen.getByTestId('estado-selo')).toBeTruthy())
    expect(screen.getByTestId('estado-selo').textContent).toContain('2 selo(s) ancorado(s). Último há 2 hora(s)')
    expect(screen.getByTestId('estado-selo').textContent).toContain('O selo diário está em dia.')
    expect(screen.getByTestId('estado-selo').className).toContain('text-regular')
    const itens = within(ancSec()).getAllByRole('listitem')
    expect(itens.length).toBe(2); expect(itens[0].textContent).toContain('Registro nº 2'); expect(itens[1].textContent).toContain('Registro nº 1')
    fireEvent.click(screen.getByText('Verificar lastro'))
    await waitFor(() => expect(itens[1].textContent).toContain('Lastro coerente: o registro não foi alterado desde a ancoragem.'))
    expect(itens[0].textContent).toContain('Lastro quebrado: registro nº 2 reescrito')
    fireEvent.click(within(itens[0]).getByText('Selo (.txt)'))
    expect(baixar).toHaveBeenLastCalledWith('selo-2.txt', expect.stringContaining('selo: selo-dois-'), 'text/plain')
    fireEvent.click(within(itens[0]).getByText('Prova (.ots)'))
    expect(baixar).toHaveBeenLastCalledWith('selo-2.txt.ots', new Uint8Array([7]), undefined)
    fireEvent.click(screen.getByTestId('copiar-selo'))
    expect(write.mock.calls[0][0]).toContain('Selo (SHA-256): selo-dois-'); expect(write.mock.calls[0][0]).toContain('Total de selos ancorados: 2')
    fireEvent.click(screen.getByTestId('copiar-selos'))
    await waitFor(() => expect(screen.getByTestId('copiar-selos').textContent).toBe('Lista de selos copiada'))
    expect(write.mock.calls[1][0].split('\n').length).toBe(3); expect(write.mock.calls[1][0]).toContain('nº 2 ·')
    const clique = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => undefined)
    fireEvent.click(screen.getByTestId('baixar-selos'))
    expect(screen.getByTestId('baixar-selos').textContent).toBe('Baixado'); expect(clique).toHaveBeenCalledTimes(1)
    fireEvent.click(screen.getByTestId('imprimir-selos')); expect(window.print).toHaveBeenCalled()
    fireEvent.click(screen.getByTestId('copiar-link-selos'))
    await waitFor(() => expect(screen.getByTestId('copiar-link-selos').textContent).toBe('Link copiado'))
    ancoragens = [...ancoragens, { id: 'a9', seq: 3, selo: 's9', digest: 'ab', calendario: 'https://alice', provaB64: 'AA==', em: horasAtras(0) }]
    fireEvent.click(screen.getByText('Ancorar selo agora'))
    expect(screen.getByText('Enviando…')).toBeTruthy()
    await waitFor(() => expect(screen.getByRole('status').textContent).toBe('Selo do registro nº 3 enviado. A confirmação no Bitcoin leva algumas horas.'))
    expect(within(ancSec()).getAllByRole('listitem').length).toBe(3)
    expect(screen.queryByText(/Lastro quebrado/)).toBeNull()
    ancorar.mockRejectedValueOnce(new Error('Ainda não há registros na trilha para ancorar.'))
    fireEvent.click(screen.getByText('Ancorar selo agora'))
    await waitFor(() => expect(screen.getByRole('alert').textContent).toBe('Ainda não há registros na trilha para ancorar.'))
    clique.mockRestore()
    cleanup(); ancoragens = [ancoragens[0]]
    render(<TrilhaPage />)
    await waitFor(() => expect(screen.getByTestId('estado-selo').textContent).toContain('Último há 30 hora(s)'))
    expect(screen.getByTestId('estado-selo').textContent).toContain('O selo diário está em dia.')
    cleanup(); ancoragens = [{ ...ancoragens[0], em: horasAtras(40) }]
    render(<TrilhaPage />)
    await waitFor(() => expect(screen.getByTestId('estado-selo').textContent).toContain('Último há 40 hora(s)'))
    expect(screen.getByTestId('estado-selo').textContent).toContain('O selo diário deveria ter rodado; use "Ancorar selo agora".')
    expect(screen.getByTestId('estado-selo').className).toContain('text-atencao')
  })

  it('exportação por período com atalhos de datas, PDF e selo baixados, hash e calendário informados; sem calendário avisa; erro; trilha vazia', async () => {
    render(<TrilhaPage />)
    await waitFor(() => expect(screen.getByTestId('contagem-trilha')).toBeTruthy())
    const hoje = new Date().toISOString().slice(0, 10)
    expect((screen.getByTestId('exportar-ate') as HTMLInputElement).value).toBe(hoje)
    expect((screen.getByTestId('exportar-de') as HTMLInputElement).value).toBe(new Date(Date.now() - 30 * 86400000).toISOString().slice(0, 10))
    fireEvent.click(screen.getByText('7 dias'))
    expect((screen.getByTestId('exportar-de') as HTMLInputElement).value).toBe(new Date(Date.now() - 7 * 86400000).toISOString().slice(0, 10))
    fireEvent.click(screen.getByText('mês passado'))
    const d = new Date(); const ini = new Date(d.getFullYear(), d.getMonth() - 1, 1).toISOString().slice(0, 10); const fim = new Date(d.getFullYear(), d.getMonth(), 0).toISOString().slice(0, 10)
    expect((screen.getByTestId('exportar-de') as HTMLInputElement).value).toBe(ini); expect((screen.getByTestId('exportar-ate') as HTMLInputElement).value).toBe(fim)
    fireEvent.change(screen.getByTestId('exportar-de'), { target: { value: '2026-10-01' } })
    fireEvent.change(screen.getByTestId('exportar-ate'), { target: { value: '2026-10-31' } })
    fireEvent.click(screen.getByTestId('exportar-pdf-selo'))
    expect(screen.getByText('Gerando e selando…')).toBeTruthy()
    await waitFor(() => expect(screen.getByTestId('msg-exportacao')).toBeTruthy())
    expect(exportar).toHaveBeenCalledWith('2026-10-01', '2026-10-31')
    expect(baixar).toHaveBeenCalledWith('trilha-2026-10.pdf', new Uint8Array([1]), 'application/pdf')
    await waitFor(() => expect(baixar).toHaveBeenCalledWith('trilha-2026-10.pdf.ots', new Uint8Array([2]), undefined), { timeout: 1500 })
    expect(screen.getByTestId('msg-exportacao').textContent).toContain(`2 registro(s) exportado(s). SHA-256 do PDF: ${'f'.repeat(64)}. Selo enviado a alice.btc.calendar.opentimestamps.org; a confirmação no Bitcoin leva algumas horas.`)
    exportar.mockResolvedValueOnce({ nomeBase: 'trilha-x', pdf: new Uint8Array([1]), ots: null as unknown as Uint8Array<ArrayBuffer>, sha256: 'e'.repeat(64), total: 0, calendario: null as unknown as string })
    fireEvent.click(screen.getByTestId('exportar-pdf-selo'))
    await waitFor(() => expect(screen.getByTestId('msg-exportacao').textContent).toContain('Selo não obtido agora (calendários fora do ar); o PDF e o hash valem, tente selar de novo mais tarde.'))
    exportar.mockRejectedValueOnce(new Error('Não há registros no período.'))
    fireEvent.click(screen.getByTestId('exportar-pdf-selo'))
    await waitFor(() => expect(screen.getByRole('alert').textContent).toBe('Não há registros no período.'))
    expect(screen.queryByTestId('msg-exportacao')).toBeNull()
    cleanup(); eventos = []; verificacao = { integra: true, total: 0, selo: '' }
    render(<TrilhaPage />)
    await waitFor(() => expect(screen.getByText('Nenhum registro ainda. Cadastre um imóvel ou contrato para iniciar a trilha.')).toBeTruthy())
    expect(screen.queryByTestId('filtros-trilha')).toBeNull()
    expect(screen.getByTestId('estado-selo').textContent).toContain('Nenhum selo ainda.')
    expect((screen.getByText('Ancorar selo agora').closest('button') as HTMLButtonElement).disabled).toBe(true)
    expect((screen.getByText('Verificar lastro') as HTMLButtonElement).disabled).toBe(true)
  })
})
